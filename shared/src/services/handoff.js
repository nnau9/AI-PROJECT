// Когда помощник после ответа по существу предлагает связаться с командой NNATO.
//
// Используется и в браузере (локальные ответы), и на сервере чата (подсказка модели).
// Модель тоже может сама решить, что нужен сотрудник, — тогда сервер возвращает handoff: true.

// Темы, где решение принимает сотрудник: личная ситуация, деньги и договор, запись и места,
// выбор конкретного работодателя, статус заявки. Русский, казахский и английский.
const HANDOFF_PATTERNS = [
  // Оплата, договор, возврат, скидки, точная стоимость
  /оплат|оплачива|заплатить|платеж|платёж|предоплат|рассрочк|kaspi|каспи/,
  /договор|оферт/,
  /возврат|верн\S* (ли )?(мне )?(деньги|оплату|средства)|деньги (обратно|назад)/,
  /скидк|промокод|акци[яи]|дешевле для меня/,
  /точн(ая|ую|ой) (стоимост|цен|сумм)|сколько (это )?(будет )?стоить (для |лично )?(меня|мне)|итоговая сумма/,
  // Запись, бронирование, места, выбор работодателя
  /запис(ать|аться|ь на)|забронир|бронирован|брон[ья] (места|мест)|свободн(ые|ых) мест|остались ли места/,
  /(выбрать|подобрать|найти мне|подберите|подбери) (конкретн\S* )?(работодател|работу|вакансию|место работы)|какой работодатель (мне|подойд)/,
  // Статус заявки
  /статус (моей |мое[йё] )?заявк|моя заявка|мою заявку|по моей заявке|что с (моей )?заявк|когда (мне )?ответят/,
  // Личная ситуация
  /подхожу ли|подойду ли|я подхожу|я подойду|мне подойдет|мне подойдёт|в моем случае|в моём случае|мой случай|моя ситуация|у меня (есть |была |был )?(судимост|долг|отказ|академ|виза|загранпаспорт)/,
  /(мне |меня )?(уже )?отказ(али|ал|ывали)|отказ(е|у)? в виз|был отказ|после отказа/,
  /мои документы|моих документов|мой паспорт|мой загранпаспорт|мою справку/,
  // Қазақша
  /төле(м|у|йм)|ақша(ны)? қайтар|келісімшарт|жеңілдік|өтінім(ім|нің)? (мәртебе|күй)|маған сәйкес|менің жағдай|виза(дан)? бас тарт/,
  // English
  /\b(pay|payment|paying|refund|contract|discount|promo ?code|installment)s?\b/,
  /\b(book|booking|reserve|reservation)\b|\bsign (me )?up\b|\bchoose (an |my |a specific )?employer\b/,
  /\b(status of my|my application)\b|\bam i eligible\b|\bmy (case|situation|documents|passport)\b|\b(was|been|got) (denied|refused|rejected)\b|\bvisa (denial|refusal)\b/,
];

const normalize = (text) => String(text ?? '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();

/** true, если вопрос лучше передать команде NNATO (после ответа по существу). */
export function needsTeam(question) {
  const text = normalize(question);
  if (!text) return false;
  return HANDOFF_PATTERNS.some((re) => re.test(text));
}

